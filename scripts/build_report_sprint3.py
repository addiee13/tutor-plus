def export_pdf(docx):
    """Export with Microsoft Word. The files are staged inside Word's sandbox container so that Word never
    shows a Grant Access dialog (which blocks AppleEvents and made docx2pdf time out or export the wrong file)."""
    import shutil

    WORD_DIR.mkdir(parents=True, exist_ok=True)
    staged = WORD_DIR / docx.name
    staged_pdf = staged.with_suffix(".pdf")
    shutil.copy2(docx, staged)
    staged_pdf.unlink(missing_ok=True)
    script = WORD_DIR / "export.js"
    script.write_text(JXA)
    subprocess.run(["osascript", "-l", "JavaScript", str(script), str(staged), str(staged_pdf)], check=True, timeout=900)
    pdf = docx.with_suffix(".pdf")
    shutil.copy2(staged_pdf, pdf)
    import pymupdf
    first = pymupdf.open(pdf)[0].get_text()
    if "Group 11" not in first or "Tutor Plus" not in first:
        raise SystemExit("Exported PDF is not the Group 11 Tutor Plus report")
    return pdf


def page_map(pdf):
    import pymupdf

    headings = json.loads(HEADINGS_FILE.read_text())
    doc = pymupdf.open(pdf)
    pages = [[" ".join(l.split()) for l in page.get_text().splitlines()] for page in doc]
    start = next(i for i, lines in enumerate(pages) if "TABLE OF CONTENTS" in lines)
    body = start + 1
    while body < len(pages) and sum(1 for l in pages[body] if re.search(r"\.{4,}\s*\d+$|\t\d+$", l)) > 3:
        body += 1
    result, cursor = [], body
    for level, text in headings:
        norm = " ".join(text.split())
        hit = next((i for i in range(cursor, len(pages)) if norm in pages[i]), None)
        if hit is None:
            raise SystemExit(f"Heading not found in PDF: {text}")
        result.append([level, text, hit + 1])
        cursor = hit
    return result, len(doc)


def main():
    docx, _ = build_docx()
    if "--docx" in sys.argv:
        print(docx)
        return
    for attempt in range(4):
        pdf = export_pdf(docx)
        entries, pages = page_map(pdf)
        previous = json.loads(TOC_FILE.read_text()) if TOC_FILE.exists() else None
        print(f"pass {attempt + 1}: {pages} pages")
        if previous == entries:
            break
        TOC_FILE.write_text(json.dumps(entries))
        docx, _ = build_docx()
    print(json.dumps({"docx": str(docx), "pdf": str(pdf), "pages": pages, "placeholders": len(PLACEHOLDERS)}))


if __name__ == "__main__":
    main()
