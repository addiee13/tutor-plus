class Report:
    def __init__(self):
        self.doc = Document()
        self.fig = 0
        self.tab = 0
        self.refs: dict[str, int] = {}
        self.headings: list[list] = []
        self.landscape = False

    # ------------------------------------------------------------------ page setup
    def configure(self):
        doc = self.doc
        s = doc.sections[0]
        s.page_width, s.page_height = Inches(8.5), Inches(11)
        for side in ("top_margin", "bottom_margin", "left_margin", "right_margin"):
            setattr(s, side, Inches(1))
        s.header_distance = Inches(0.5)
        s.footer_distance = Inches(0.5)
        normal = doc.styles["Normal"]
        normal.font.name = "Times New Roman"
        normal.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        normal.font.size = Pt(12)
        pf = normal.paragraph_format
        pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        pf.space_after = Pt(6)
        pf.line_spacing = 1.15
        pf.widow_control = True
        for name in ("List Bullet", "List Number"):
            st = doc.styles[name]
            st.font.name = "Times New Roman"
            st.font.size = Pt(12)
            st.paragraph_format.space_after = Pt(3)
            st.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        for level, size in ((1, 14), (2, 13), (3, 12)):
            st = doc.styles[f"Heading {level}"]
            st.font.name = "Times New Roman"
            st.element.rPr.rFonts.set(qn("w:asciiTheme"), "") if False else None
            rfonts = st.element.rPr.find(qn("w:rFonts"))
            if rfonts is not None:
                for key in ("w:asciiTheme", "w:hAnsiTheme", "w:eastAsiaTheme", "w:cstheme"):
                    rfonts.attrib.pop(qn(key), None)
                rfonts.set(qn("w:ascii"), "Times New Roman")
                rfonts.set(qn("w:hAnsi"), "Times New Roman")
            st.font.size = Pt(size)
            st.font.bold = True
            st.font.italic = False
            st.font.color.rgb = RGBColor(0, 0, 0)
            st.paragraph_format.space_before = Pt(12 if level == 1 else 10)
            st.paragraph_format.space_after = Pt(6)
            st.paragraph_format.keep_with_next = True
            st.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
        cap = doc.styles["Caption"]
        cap.font.name = "Times New Roman"
        cap.font.size = Pt(11)
        cap.font.bold = True
        cap.font.italic = False
        cap.font.color.rgb = RGBColor(0, 0, 0)
        cap.paragraph_format.space_before = Pt(3)
        cap.paragraph_format.space_after = Pt(10)
        cap.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        self.header_footer(s, 6.5)
        doc.core_properties.title = "Tutor Plus: Smart Platform for Academic Progress, Sprint 3"
        doc.core_properties.author = "Group 11: Edu M. Okpok, Shadmaan Akhand, Adam Dalwai, Kien Duong, Nikhil Rodrigo"
        doc.core_properties.subject = "Software Engineering Project, Fall 2026"

    def header_footer(self, section, width):
        header = section.header
        header.is_linked_to_previous = False
        p = header.paragraphs[0]
        p.text = ""
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.tab_stops.add_tab_stop(Inches(width), WD_TAB_ALIGNMENT.RIGHT)
        p.paragraph_format.space_after = Pt(0)
        for text, underline in (("Group 11", False), ("\t", True), ("Software Engineering Project", False)):
            run = p.add_run(text)
            run.font.size = Pt(11)
            run.font.name = "Times New Roman"
            run.underline = underline
        footer = section.footer
        footer.is_linked_to_previous = False
        f = footer.paragraphs[0]
        f.text = ""
        f.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        self.field(f, " PAGE ")

    def field(self, paragraph, instruction):
        run = paragraph.add_run()
        run.font.size = Pt(11)
        for kind, text in (("begin", None), (None, instruction), ("separate", None)):
            if kind:
                el = OxmlElement("w:fldChar")
                el.set(qn("w:fldCharType"), kind)
            else:
                el = OxmlElement("w:instrText")
                el.set(qn("xml:space"), "preserve")
                el.text = text
            run._r.append(el)
        run2 = paragraph.add_run("1")
        run2.font.size = Pt(11)
        end = OxmlElement("w:fldChar")
        end.set(qn("w:fldCharType"), "end")
        paragraph.add_run()._r.append(end)

    def orientation(self, landscape):
        if landscape == self.landscape:
            return
        s = self.doc.add_section(WD_SECTION_START.NEW_PAGE)
        s.orientation = WD_ORIENT.LANDSCAPE if landscape else WD_ORIENT.PORTRAIT
        s.page_width, s.page_height = (Inches(11), Inches(8.5)) if landscape else (Inches(8.5), Inches(11))
        for side in ("top_margin", "bottom_margin", "left_margin", "right_margin"):
            setattr(s, side, Inches(1))
        self.header_footer(s, 9 if landscape else 6.5)
        self.landscape = landscape

    @property
    def width(self):
        return 9.0 if self.landscape else 6.5

    @property
    def height(self):
        return 6.5 if self.landscape else 9.0

    # ------------------------------------------------------------------ text helpers
    def inline(self, paragraph, text, size=None, bold=False):
        for piece in re.split(r"(\*\*.*?\*\*)", text):
            if not piece:
                continue
            strong = piece.startswith("**") and piece.endswith("**")
            run = paragraph.add_run(piece[2:-2] if strong else piece)
            run.bold = strong or bold
            if size:
                run.font.size = Pt(size)
        return paragraph

    def para(self, text, keep=False, align=None, size=None, space_after=None, indent=None):
        p = self.doc.add_paragraph()
        self.inline(p, text, size)
        if keep:
            p.paragraph_format.keep_with_next = True
        if align is not None:
            p.alignment = align
        if space_after is not None:
            p.paragraph_format.space_after = Pt(space_after)
        if indent is not None:
            p.paragraph_format.left_indent = Inches(indent)
        return p

    def paras(self, key, **fmt):
        for text in C.TEXT[key]:
            self.para(text.format(**fmt) if fmt else text)

    def labeled(self, label, text="", keep=False):
        p = self.doc.add_paragraph()
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.keep_with_next = keep
        p.add_run(label + (" " if text else "")).bold = True
        self.inline(p, text)
        return p

    def bullets(self, items, size=None):
        for item in items:
            p = self.doc.add_paragraph(style="List Bullet")
            if isinstance(item, tuple):
                p.add_run(item[0] + " ").bold = True
                self.inline(p, item[1], size)
            else:
                self.inline(p, item, size)

    def numbered(self, items, keep=False):
        for n, item in enumerate(items, 1):
            p = self.doc.add_paragraph()
            p.paragraph_format.left_indent = Inches(0.5)
            p.paragraph_format.first_line_indent = Inches(-0.25)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.keep_with_next = keep
            self.inline(p, f"{n}. {item}")

    def heading(self, text, level=1, page_break=False, toc=True):
        p = self.doc.add_heading(text, level=level)
        p.paragraph_format.page_break_before = page_break
        if toc and level <= 2:
            self.headings.append([level, text])
        return p

    def page_break(self):
        self.doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    def placeholder(self, text):
        PLACEHOLDERS.append(text)
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        border = OxmlElement("w:pBdr")
        for side in ("top", "left", "bottom", "right"):
            el = OxmlElement(f"w:{side}")
            for k, v in (("val", "single"), ("sz", "8"), ("space", "6"), ("color", "000000")):
                el.set(qn(f"w:{k}"), v)
            border.append(el)
        p._p.get_or_add_pPr().append(border)
        run = p.add_run(f"[PLACEHOLDER: {text}]")
        run.bold = True
        run.italic = True
        return p

    # ------------------------------------------------------------------ figures and tables
    def ref(self, key):
        return "{%s}" % key

    def figure(self, path, caption, key=None, max_h=None, max_w=None, border=False):
        path = Path(path)
        if not path.exists():
            self.placeholder(f"missing image {path.relative_to(ROOT)} ({caption})")
            return
        img = Image.open(path)
        w = max_w or self.width
        h = max_h or (self.height - 0.75)
        width = min(w, h * img.width / img.height)
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.keep_with_next = True
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.space_before = Pt(4)
        run = p.add_run()
        pic = run.add_picture(str(path), width=Inches(width))
        if border:
            spPr = pic._inline.graphic.graphicData.pic.spPr
            ln = OxmlElement("a:ln")
            ln.set("w", "9525")
            fill = OxmlElement("a:solidFill")
            clr = OxmlElement("a:srgbClr")
            clr.set("val", "808080")
            fill.append(clr)
            ln.append(fill)
            spPr.append(ln)
        self.fig += 1
        if key:
            self.refs[f"F:{key}"] = self.fig
        cap = self.doc.add_paragraph(style="Caption")
        self.inline(cap, f"Figure {self.fig}: {caption}")
        return width

    def table(self, headers, rows, widths, caption, key=None, size=10, bold_first=False, align_left=True):
        self.tab += 1
        if key:
            self.refs[f"T:{key}"] = self.tab
        cap = self.doc.add_paragraph(style="Caption")
        cap.paragraph_format.keep_with_next = True
        cap.paragraph_format.space_after = Pt(4)
        self.inline(cap, f"Table {self.tab}: {caption}")
        t = self.doc.add_table(rows=1, cols=len(headers))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        t.autofit = False
        hdr = t.rows[0]
        hdr._tr.get_or_add_trPr().append(OxmlElement("w:tblHeader"))
        for cell, text in zip(hdr.cells, headers):
            shade = OxmlElement("w:shd")
            shade.set(qn("w:val"), "clear")
            shade.set(qn("w:fill"), "E7E6E6")
            cell._tc.get_or_add_tcPr().append(shade)
            cell.paragraphs[0].add_run(text).bold = True
        for values in rows:
            cells = t.add_row().cells
            for i, (cell, text) in enumerate(zip(cells, values)):
                self.inline(cell.paragraphs[0], str(text), bold=bold_first and i == 0)
        for row in t.rows:
            row._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
            for cell, w in zip(row.cells, widths):
                cell.width = Inches(w)
                cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.TOP
                for p in cell.paragraphs:
                    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                    p.paragraph_format.space_after = Pt(1)
                    p.paragraph_format.space_before = Pt(1)
                    p.paragraph_format.line_spacing = 1.0
                    for r in p.runs:
                        r.font.size = Pt(size)
        # Small tables move as one block (caption, header, rows); long tables split between rows with a repeated header.
        rows_to_keep = t.rows[:-1] if len(rows) <= 8 else t.rows[:1]
        for row in rows_to_keep:
            for cell in row.cells:
                for p in cell.paragraphs:
                    p.paragraph_format.keep_with_next = True
        spacer = self.doc.add_paragraph()
        spacer.paragraph_format.space_after = Pt(4)
        spacer.paragraph_format.line_spacing = 0.8
        return t

    def code(self, lines, size=9.5):
        t = self.doc.add_table(rows=1, cols=1)
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        cell = t.rows[0].cells[0]
        cell.width = Inches(self.width - 0.2)
        first = True
        for line in lines:
            p = cell.paragraphs[0] if first else cell.add_paragraph()
            first = False
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.0
            r = p.add_run(line)
            r.font.name = "Courier New"
            r.font.size = Pt(size)
        self.doc.add_paragraph().paragraph_format.space_after = Pt(2)

    # ------------------------------------------------------------------ token resolution
    def resolve(self):
        pattern = re.compile(r"\{([FT]:[a-z0-9_]+)\}")

        def fix(paragraph):
            for run in paragraph.runs:
                if "{" in run.text:
                    run.text = pattern.sub(lambda m: str(self.refs.get(m.group(1), "??")), run.text)

        for p in self.doc.paragraphs:
            fix(p)
        for t in self.doc.tables:
            for row in t.rows:
                for cell in row.cells:
                    for p in cell.paragraphs:
                        fix(p)


