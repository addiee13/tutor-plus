def relationships(schema, name):
    t = schema[name]
    lines = []
    uniques = [set(u) for u in t["uniques"]] + [set(t["pk"])]
    for fk in t["fks"]:
        parent = "auth.users" if fk["table"] == "users" else fk["table"]
        cols = ", ".join(fk["columns"])
        one = set(fk["columns"]) in uniques
        nullable = all("not null" not in c["constraints"].lower() and c["name"] not in t["pk"]
                       for c in t["columns"] if c["name"] in fk["columns"])
        if len(fk["columns"]) > 1:
            lines.append(f"{name}.({cols}) must match a {parent} row (composite foreign key).")
            continue
        lines.append(f"{parent} ({'0..1' if nullable else '1'}) to {name} ({'0..1' if one else '0..*'}), through {name}.{cols}.")
    for other, ot in schema.items():
        if other == name:
            continue
        ou = [set(u) for u in ot["uniques"]] + [set(ot["pk"])]
        for fk in ot["fks"]:
            if fk["table"] == name and len(fk["columns"]) == 1:
                one = set(fk["columns"]) in ou
                nullable = all("not null" not in c["constraints"].lower() and c["name"] not in ot["pk"]
                               for c in ot["columns"] if c["name"] in fk["columns"])
                lines.append(f"{name} ({'0..1' if nullable else '1'}) to {other} ({'0..1' if one else '0..*'}), through {other}.{fk['columns'][0]}.")
    return lines or ["No foreign-key relationships (a single-row control table)."]


def clean_constraints(text):
    text = re.sub(r"references [\w.]+\(\w+\)( on delete \w+)?", "", text, flags=re.I)
    text = re.sub(r"\bprimary key\b", "", text, flags=re.I)
    text = re.sub(r"\bunique\b", "UNIQUE", text)
    text = re.sub(r"\bnot null\b", "NOT NULL", text)
    text = re.sub(r"\bdefault\b", "DEFAULT", text)
    text = re.sub(r"\bcheck\b", "CHECK", text)
    text = text.replace("public.", "").replace("extensions.", "")
    return " ".join(text.split()) or "-"


